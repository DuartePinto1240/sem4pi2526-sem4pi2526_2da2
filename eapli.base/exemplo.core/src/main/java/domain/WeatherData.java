package domain;

import domain.AirControlAreaCode;
import eapli.framework.domain.model.AggregateRoot;
import eapli.framework.validations.Preconditions;

import jakarta.persistence.Column;
import jakarta.persistence.Embedded;
import jakarta.persistence.EmbeddedId;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Table;

/**
 * Aggregate Root representing a weather data record in the AISafe system (US041).
 *
 * <p>A weather data record captures wind conditions observed in a specific
 * rectangular sub-area ({@link WeatherSubArea}) of an air control area, over
 * a defined time period ({@link ObservationPeriod}).</p>
 *
 * <p>Domain invariants enforced by this class:</p>
 * <ul>
 *   <li>The area code reference must not be null.</li>
 *   <li>The sub-area boundary must not be null.</li>
 *   <li>The observation period must not be null (period end > period start is
 *       enforced by {@link ObservationPeriod} itself).</li>
 *   <li>Wind conditions must not be null (direction [0,360[ and speed ≥ 0 are
 *       enforced by {@link WindCondition} itself).</li>
 * </ul>
 *
 * <p><b>Aggregate boundary note:</b> {@code WeatherData} references
 * {@link AirControlArea} by its identity ({@link AirControlAreaCode}) only.
 * No direct object reference is held, preserving aggregate boundary rules.</p>
 *
 * <p><b>Simplification note (MVP):</b> altitude layers are not modelled in
 * this sprint. The sub-area is treated as spanning the full vertical extent
 * of the air control area. See {@link WeatherSubArea} for details.</p>
 */
@Entity
@Table(name = "WEATHER_DATA")
public class WeatherData implements AggregateRoot<WeatherDataId> {

    /** Surrogate identity — auto-generated by JPA on first persist. */
    @EmbeddedId
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private WeatherDataId id;

    /**
     * Reference to the air control area by identity (code).
     * Stored as a column, not a FK join — preserves aggregate boundaries.
     */
    @Embedded
    private AirControlAreaCode areaCode;

    /** The rectangular sub-area within the air control area. */
    @Embedded
    private WeatherSubArea subArea;

    /** The time period during which this observation is valid. */
    @Embedded
    private ObservationPeriod period;

    /** Wind direction and speed at the time of observation. */
    @Embedded
    private WindCondition wind;

    /**
     * Creates a new WeatherData record.
     *
     * @param areaCode reference to the air control area (by code)
     * @param subArea  rectangular sub-area within the air control area
     * @param period   observation time period (end must be after start)
     * @param wind     wind direction and speed
     * @throws IllegalArgumentException if any argument is null
     */
    public WeatherData(final AirControlAreaCode areaCode,
                       final WeatherSubArea subArea,
                       final ObservationPeriod period,
                       final WindCondition wind) {
        Preconditions.nonNull(areaCode, "Area code must not be null");
        Preconditions.nonNull(subArea,  "Sub-area must not be null");
        Preconditions.nonNull(period,   "Observation period must not be null");
        Preconditions.nonNull(wind,     "Wind condition must not be null");

        this.areaCode = areaCode;
        this.subArea  = subArea;
        this.period   = period;
        this.wind     = wind;
    }

    /** {@inheritDoc} */
    @Override
    public WeatherDataId identity() {
        return id;
    }

    /** {@inheritDoc} */
    @Override
    public boolean sameAs(final Object other) {
        if (!(other instanceof WeatherData)) return false;
        final WeatherData that = (WeatherData) other;
        return this.areaCode.equals(that.areaCode)
                && this.subArea.equals(that.subArea)
                && this.period.equals(that.period);
    }

    /** @return the air control area code this data belongs to */
    public AirControlAreaCode areaCode() {
        return areaCode;
    }

    /** @return the sub-area within the air control area */
    public WeatherSubArea subArea() {
        return subArea;
    }

    /** @return the time period for which this data is valid */
    public ObservationPeriod period() {
        return period;
    }

    /** @return the wind conditions recorded */
    public WindCondition wind() {
        return wind;
    }

    @Override
    public String toString() {
        return String.format("WeatherData[area=%s, subArea=%s, period=%s, wind=%s]",
                areaCode, subArea, period, wind);
    }

    /** No-arg constructor required by JPA. */
    protected WeatherData() {
    }
}
