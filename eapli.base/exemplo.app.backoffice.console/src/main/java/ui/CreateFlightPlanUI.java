package ui;

import controller.CreateFlightPlanController;
import domain.GeographicBoundary;
import domain.aircraft.Aircraft;
import domain.flightroute.FlightRoute;
import domain.pilot.Pilot;
import lprog.FlightLeg;
import lprog.FlightPlan;
import lprog.FlightSegment;
import eapli.framework.io.util.Console;
import eapli.framework.presentation.console.AbstractUI;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.time.format.DateTimeParseException;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

public class CreateFlightPlanUI extends AbstractUI {

    private static final DateTimeFormatter DT_FMT =
            DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm");

    @Override
    protected boolean doShow() {
        final CreateFlightPlanController ctrl = new CreateFlightPlanController();

        System.out.println("\n--- Create Flight Plan ---");

        // -- 1. Pilot — resolved first so route list can be filtered ----------
        final Optional<Pilot> pilotOpt = ctrl.currentPilot();
        if (pilotOpt.isEmpty()) {
            System.out.println("\n>> ERROR: No pilot profile found for your account.");
            System.out.println("   Please ask an ATCC collaborator to register you as a pilot (US075).");
            return false;
        }
        final Pilot pilot = pilotOpt.get();
        System.out.printf("%nPilot: %s (%s) [%s]%n",
                pilot.name(), pilot.email(),
                pilot.company().companyCode().iata());

        // -- 2. Select route (filtered by pilot's company) --------------------
        final FlightRoute route = selectRoute(ctrl, pilot);
        if (route == null) return false;

        // -- 3. Select aircraft -----------------------------------------------
        final Aircraft aircraft = selectAircraft(ctrl, route);
        if (aircraft == null) return false;

        // -- 4. Flight ID -----------------------------------------------------
        final String flightId = Console.readLine("Flight ID (e.g. TP001):");
        if (flightId == null || flightId.isBlank()) {
            System.out.println(">> Flight ID cannot be empty. Operation cancelled.");
            return false;
        }

        // -- 5. Departure date/time (for leg 1) -------------------------------
        final LocalDateTime departure = readDepartureDateTime();
        if (departure == null) return false;

        // -- 6. Legs (airports pre-filled from route; segments collected) -----
        final List<FlightLeg> legs = readLegs(ctrl, route, departure);
        if (legs == null) return false;

        // -- 7. Create (DSL is auto-generated by the controller) --------------
        try {
            final FlightPlan plan =
                    ctrl.createFlightPlan(flightId, route, aircraft, pilot, departure, legs);

            System.out.printf("%n>> Flight plan created successfully.%n");
            System.out.printf("   Flight ID  : %s%n", plan.flightId());
            System.out.printf("   Type       : %s%n", plan.flightType());
            System.out.printf("   Route      : %s%n", plan.routeDesignator());
            System.out.printf("   Aircraft   : %s%n", plan.aircraftRegistration());
            System.out.printf("   Legs       : %d%n", plan.legs().size());
            for (int i = 0; i < plan.legs().size(); i++) {
                final FlightLeg leg = plan.legs().get(i);
                System.out.printf("     Leg %d  : %s %s %s -> %s %s | fuel: %.0f %s | segments: %d%n",
                        i + 1,
                        leg.departureAirport(), leg.departureDate(), leg.departureTime(),
                        leg.arrivalAirport(),   leg.arrivalTime(),
                        leg.fuelQuantity(),     leg.fuelUnit(),
                        leg.segments().size());
            }
            System.out.printf("   Status     : %s%n", plan.status());
            System.out.printf("   DSL stored : yes%n");

        } catch (final IllegalArgumentException e) {
            System.out.println("\n>> ERROR: " + e.getMessage());
            System.out.println(">> Flight plan was NOT created.");
        }

        return false;
    }

    // -------------------------------------------------------------------------

    private FlightRoute selectRoute(final CreateFlightPlanController ctrl, final Pilot pilot) {
        final List<FlightRoute> routes = new ArrayList<>();
        ctrl.activeRoutesForPilot(pilot).forEach(routes::add);

        if (routes.isEmpty()) {
            System.out.printf("%n>> No active routes found for company %s. Please create a route first (US073).%n",
                    pilot.company().companyCode().iata());
            return null;
        }

        System.out.println("\nAvailable routes:");
        for (int i = 0; i < routes.size(); i++) {
            final FlightRoute r = routes.get(i);
            System.out.printf("  %d. %s  %s -> %s  [%s]%n",
                    i + 1, r.identity(), r.originIata(), r.destinationIata(), r.companyIata());
        }

        final int choice = Console.readInteger("Select route:");
        if (choice < 1 || choice > routes.size()) {
            System.out.println(">> Invalid option. Operation cancelled.");
            return null;
        }
        return routes.get(choice - 1);
    }

    private Aircraft selectAircraft(final CreateFlightPlanController ctrl,
                                    final FlightRoute route) {
        final List<Aircraft> aircraft = new ArrayList<>();
        ctrl.aircraftForRoute(route).forEach(aircraft::add);

        if (aircraft.isEmpty()) {
            System.out.printf("%n>> No aircraft found for company %s.%n", route.companyIata());
            return null;
        }

        System.out.println("\nAvailable aircraft:");
        for (int i = 0; i < aircraft.size(); i++) {
            final Aircraft a = aircraft.get(i);
            System.out.printf("  %d. %s  (%s)%n", i + 1, a.registration(), a.operationalStatus());
        }

        final int choice = Console.readInteger("Select aircraft:");
        if (choice < 1 || choice > aircraft.size()) {
            System.out.println(">> Invalid option. Operation cancelled.");
            return null;
        }
        return aircraft.get(choice - 1);
    }

    private LocalDateTime readDepartureDateTime() {
        System.out.println("\nDeparture date and time for leg 1 (format: yyyy-MM-dd HH:mm):");
        final String input = Console.readLine("Departure:");
        try {
            return LocalDateTime.parse(input.trim(), DT_FMT);
        } catch (final DateTimeParseException e) {
            System.out.println(">> Invalid date/time format. Operation cancelled.");
            return null;
        }
    }

    /**
     * Collects legs from the user. Validates each leg's segment coordinates
     * immediately after collection, before moving on to the next leg.
     */
    private List<FlightLeg> readLegs(final CreateFlightPlanController ctrl,
                                      final FlightRoute route,
                                      final LocalDateTime departure) {
        final List<FlightLeg> legs = new ArrayList<>();

        System.out.printf("%nRoute: %s -> %s%n", route.originIata(), route.destinationIata());
        System.out.println("Enter legs. For a direct flight, the arrival airport is pre-filled.");
        System.out.println("For stopovers, enter the intermediate arrival airport; press Enter on the last leg to use the destination.\n");

        final String depDate = departure.toLocalDate().toString();
        final String depTime = String.format("%02d:%02d",
                departure.getHour(), departure.getMinute());

        String currentDepAirport = route.originIata();
        String currentDepDate    = depDate;
        String currentDepTime    = depTime;
        int legNum = 1;

        while (true) {
            System.out.printf("Leg %d:%n", legNum);
            System.out.printf("  Departure airport : %s (pre-filled from %s)%n",
                    currentDepAirport, legNum == 1 ? "route origin" : "previous leg arrival");
            System.out.printf("  Departure         : %s %s (pre-filled)%n", currentDepDate, currentDepTime);

            final String prompt = String.format(
                    "  Arrival airport (press Enter for final destination '%s', or type stopover IATA): ",
                    route.destinationIata());
            final String arrRaw = Console.readLine(prompt).trim();
            final String arrAirport = arrRaw.isEmpty() ? route.destinationIata() : arrRaw;

            final String arrTime  = Console.readLine("  Arrival time (HH:mm):").trim();
            final String fuelStr  = Console.readLine("  Fuel quantity (kg):").trim();

            final double fuel;
            try {
                fuel = Double.parseDouble(fuelStr);
            } catch (final NumberFormatException e) {
                System.out.println("  >> Invalid fuel quantity. Leg discarded. Try again.");
                continue;
            }

            final FlightLeg leg;
            try {
                leg = new FlightLeg(currentDepAirport, currentDepDate, currentDepTime,
                        arrAirport, arrTime, fuel, "kg");
            } catch (final IllegalArgumentException e) {
                System.out.println("  >> " + e.getMessage() + " Leg discarded. Try again.");
                continue;
            }

            // Collect segments (show boundary hint from the departure airport)
            readSegments(ctrl, leg, legNum);

            // Validate coordinates immediately — don't wait until the end
            try {
                ctrl.validateLegCoordinates(leg);
            } catch (final IllegalArgumentException e) {
                System.out.println("\n  >> ERRO nas coordenadas da leg " + legNum + ": " + e.getMessage());
                System.out.println("  >> Leg descartada. Introduz a leg novamente.\n");
                continue;
            }

            legs.add(leg);
            System.out.printf("  >> Leg %d adicionada (%d segmento(s)).%n%n", legNum, leg.segments().size());

            // If arrival = destination, we're done
            if (arrAirport.equalsIgnoreCase(route.destinationIata())) {
                break;
            }

            // Stopover: prepare next leg departure
            currentDepAirport = arrAirport;
            final String nextDepInput = Console.readLine(
                    String.format("  Departure date/time for leg %d (yyyy-MM-dd HH:mm):", legNum + 1)).trim();
            try {
                final LocalDateTime nextDep = LocalDateTime.parse(nextDepInput, DT_FMT);
                currentDepDate = nextDep.toLocalDate().toString();
                currentDepTime = String.format("%02d:%02d", nextDep.getHour(), nextDep.getMinute());
            } catch (final DateTimeParseException e) {
                System.out.println("  >> Invalid date/time. Operation cancelled.");
                return null;
            }

            legNum++;
        }

        if (legs.isEmpty()) {
            System.out.println(">> At least one leg is required. Operation cancelled.");
            return null;
        }

        return legs;
    }

    /**
     * Collects segments for a leg interactively.
     * Shows the valid coordinate boundary for the departure airport before asking for input.
     * Requires at least 3 segments: climb, cruise, descent.
     */
    private void readSegments(final CreateFlightPlanController ctrl,
                               final FlightLeg leg, final int legNum) {
        // Show boundary hint so the user knows what coordinates are valid
        final Optional<GeographicBoundary> boundary =
                ctrl.boundaryForAirport(leg.departureAirport());
        System.out.printf("%n  Segments for leg %d (min 3: climb/cruise/descent):%n", legNum);
        if (boundary.isPresent()) {
            final GeographicBoundary b = boundary.get();
            System.out.printf("  [Área de controlo de %s — lat: %.1f..%.1f | lon: %.1f..%.1f]%n",
                    leg.departureAirport(), b.minLat(), b.maxLat(), b.minLon(), b.maxLon());
        } else {
            System.out.printf("  [Área de controlo de %s não encontrada — sem validação de coordenadas]%n",
                    leg.departureAirport());
        }
        System.out.println("  (deixa 'From lat' em branco para terminar os segmentos)");

        // Build prompt suffixes with range hints when boundary is known
        final String latRange  = boundary.map(b -> String.format(" [%.1f..%.1f]", b.minLat(), b.maxLat())).orElse("");
        final String lonRange  = boundary.map(b -> String.format(" [%.1f..%.1f]", b.minLon(), b.maxLon())).orElse("");
        final String altPrompt = "      Altitude min (ft) [0..45000]: ";
        final String altMaxPrompt = "      Altitude max (ft) [0..45000]: ";

        int segNum = 1;
        while (true) {
            System.out.printf("    Segment %d:%n", segNum);

            final String fromLatStr = Console.readLine("      From lat" + latRange + " (Enter p/ terminar): ").trim();
            if (fromLatStr.isEmpty()) {
                if (leg.segments().size() < 3) {
                    System.out.println("      >> Mínimo 3 segmentos (climb, cruise, descent).");
                    continue;
                }
                break;
            }

            try {
                final String phase     = readPhase();
                final double fromLat   = Double.parseDouble(fromLatStr);
                final double fromLon   = Double.parseDouble(Console.readLine("      From lon" + lonRange + ": ").trim());
                final double toLat     = Double.parseDouble(Console.readLine("      To lat"   + latRange + ": ").trim());
                final double toLon     = Double.parseDouble(Console.readLine("      To lon"   + lonRange + ": ").trim());
                final double altMin    = Double.parseDouble(Console.readLine(altPrompt).trim());
                final double altMax    = Double.parseDouble(Console.readLine(altMaxPrompt).trim());
                final double widthM    = Double.parseDouble(Console.readLine("      Corridor width (m) [ex: 50]: ").trim());
                final double windAngle = Double.parseDouble(Console.readLine("      Wind angle (deg) [0..360]: ").trim());
                final double windSpeed = Double.parseDouble(Console.readLine("      Wind speed (m/s) [ex: 10]: ").trim());

                leg.addSegment(new FlightSegment(fromLat, fromLon, toLat, toLon,
                        altMin, altMax, phase, widthM, windAngle, windSpeed));
                System.out.printf("      >> Segment %d (%s) adicionado.%n", segNum, phase);
                segNum++;

            } catch (final NumberFormatException e) {
                System.out.println("      >> Número inválido. Segmento descartado.");
            } catch (final IllegalArgumentException e) {
                System.out.println("      >> " + e.getMessage() + " Segmento descartado.");
            }
        }
    }

    /** Prompts for a valid flight phase (climb/cruise/descent). */
    private String readPhase() {
        while (true) {
            final String phase = Console.readLine("      Phase (climb/cruise/descent):").trim().toLowerCase();
            if (phase.equals("climb") || phase.equals("cruise") || phase.equals("descent")) {
                return phase;
            }
            System.out.println("      >> Invalid phase. Enter 'climb', 'cruise', or 'descent'.");
        }
    }

    @Override
    public String headline() {
        return "US080 - Create Flight Plan";
    }
}
